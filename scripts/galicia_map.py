"""Builds the outline of Galicia that the control UI draws, faintly, behind its sidebar.

Run it only to refresh the data; the result is versioned:

    uv run scripts/galicia_map.py

Source, downloaded from a pinned URL and cached in ~/.cache/karaoke/galicia: Natural Earth
admin-1 at 1:10m (public domain), the four provinces merged and simplified.

Output: `web/src/lib/shell/galicia.ts`, the outline as an SVG path in a viewBox of
-1000 -1000 2000 2000 (+y down), in a local equirectangular projection around Galicia's centre
(east scaled by the cosine of its latitude, so the shape keeps its proportions).
"""

import json
import math
import sys
import urllib.request
from pathlib import Path

from shapely.geometry import shape
from shapely.ops import unary_union

NATURAL_EARTH = (
    "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/"
    "ca96624a56bd078437bca8184e78163e5039ad19/geojson/ne_10m_admin_1_states_provinces.geojson"
)
USER_AGENT = "galicia-outline-builder/2.0 (data script)"
CACHE = Path.home() / ".cache/karaoke/galicia"
OUT = Path(__file__).resolve().parents[1] / "web/src/lib/shell/galicia.ts"
PROVINCES = ["La Coruña", "Lugo", "Orense", "Pontevedra"]
# Degrees: about 300 m, finer than the line is drawn.
TOLERANCE = 0.003
# The widest side reaches this far from the centre of the viewBox.
HALF = 960.0
# Islets smaller than this (square degrees) are left out: they would be dots.
MIN_AREA = 0.0004


def _cached(url: str, name: str) -> Path:
    path = CACHE / name
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        print(f"downloading {url}", file=sys.stderr)
        request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})  # noqa: S310
        with urllib.request.urlopen(request, timeout=300) as response:  # noqa: S310 - pinned https
            path.write_bytes(response.read())
    return path


def galicia():  # type: ignore[no-untyped-def]
    data = json.loads(_cached(NATURAL_EARTH, "ne_10m_admin_1.geojson").read_text())
    found = {
        feature["properties"]["name"]: shape(feature["geometry"])
        for feature in data["features"]
        if feature["properties"].get("region") == "Galicia"
        and feature["properties"].get("iso_a2") == "ES"
    }
    if sorted(found) != sorted(PROVINCES):
        raise SystemExit(f"expected the four provinces of Galicia, found {sorted(found)}")
    return unary_union([found[name] for name in PROVINCES])


def outline(region) -> str:  # type: ignore[no-untyped-def]
    min_lon, min_lat, max_lon, max_lat = region.bounds
    lon0, lat0 = (min_lon + max_lon) / 2, (min_lat + max_lat) / 2
    cos0 = math.cos(math.radians(lat0))
    scale = HALF / (max((max_lon - min_lon) * cos0, max_lat - min_lat) / 2)
    simple = region.simplify(TOLERANCE, preserve_topology=True)
    polygons = sorted(getattr(simple, "geoms", [simple]), key=lambda p: -p.area)
    parts = []
    for polygon in polygons:
        if polygon.area < MIN_AREA:
            continue
        points = [
            f"{(lon - lon0) * cos0 * scale:.0f} {(lat0 - lat) * scale:.0f}"
            for lon, lat in polygon.exterior.coords[:-1]
        ]
        parts.append("M" + "L".join(points) + "Z")
    return "".join(parts)


def main() -> None:
    path = outline(galicia())
    OUT.write_text(
        "/*\n"
        " * Generated by scripts/galicia_map.py. Do not edit by hand.\n"
        " * Boundaries: Natural Earth (public domain).\n"
        " */\n\n"
        "/** Outline of Galicia as an SVG path, in a viewBox of -1000 -1000 2000 2000. */\n"
        f"export const OUTLINE =\n\t'{path}';\n"
    )
    print(f"{OUT}: {len(path) / 1024:.1f} kB", file=sys.stderr)


if __name__ == "__main__":
    main()
